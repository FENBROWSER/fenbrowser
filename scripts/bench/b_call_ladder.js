function loopOnly(n) { var t = 0; for (var i = 0; i < n; i++) t += i; return t; }
function callF0(n)   { var t = 0; for (var i = 0; i < n; i++) t += f0(); return t; }
function callF2(n)   { var t = 0; for (var i = 0; i < n; i++) t += f2(i, 1); return t; }
