var rungs = [["loop", loopOnly], ["+call0", callF0], ["+2args", callF2],
             ["+110vars", callWide], ["+native", callNative], ["+propreads", callProp]];
for (var w = 0; w < rungs.length; w++) rungs[w][1](200000);

var N = 2000000, out = "", prev = 0;
for (var w = 0; w < rungs.length; w++) {
    var best = 1e18;
    for (var r = 0; r < 3; r++) {
        var t0 = Date.now(); rungs[w][1](N); var ms = Date.now() - t0;
        if (ms < best) best = ms;
    }
    var ns = best * 1e6 / N;
    out += rungs[w][0] + "=" + ns.toFixed(0) + "ns(+" + (ns - prev).toFixed(0) + ") ";
    prev = ns;
}
out;
